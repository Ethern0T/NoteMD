#!/usr/bin/env python3
"""Generate NoteMD's GtkSourceView palettes and Markdown extension grammar."""
from pathlib import Path
import re
from xml.sax.saxutils import escape
root = Path(__file__).resolve().parents[1]
colors = {
 'catppuccin-latte': ('#8839ef','#9b4b0a','#d20f39','#e6e9ef','#1e66f5','#287d1e','#5c5f77'),
 'white': ('#3d668c','#9b501f','#6b4fa4','#eef2f6','#286b78','#397148','#526274'),
 'solarized-light': ('#326c84','#a25029','#6d5491','#eee8d5','#216d78','#577423','#53666a'),
 'black': ('#a4c5eb','#e9b788','#c7b1ea','#2a3443','#8bcbd2','#a9c795','#a8b6c9'),
 'dracula': ('#b69af5','#efbd8b','#efadc9','#343747','#93c5d7','#a6d1ad','#b4b1c6'),
 'monokai': ('#a8c775','#dfb47b','#cfb5f0','#353a2e','#9acbd4','#a8c775','#b5b9a7'),
 'tokyo-night': ('#82aaff','#e6b48d','#bda8f2','#262e43','#8dc5d5','#a9ca97','#a7b4d0'),
}
for name, (heading,emphasis,code,codebg,link,listcolor,muted) in colors.items():
 palette = dict(re.findall(r'@define-color (\w+) (#[a-fA-F0-9]{6});',(root/'themes'/f'{name}.css').read_text()))
 styles = []
 def style(key, **attributes):
  styles.append('  <style name="'+key+'" '+ ' '.join(f'{k.replace("_","-")}="{v}"' for k,v in attributes.items())+'/>' )
 style('text',foreground=palette['theme_fg_color'],background=palette['notemd_paper'])
 style('selection',foreground=palette['notemd_accent_fg'],background=palette['notemd_accent'])
 style('cursor',foreground=palette['theme_fg_color'])
 style('bracket-match',bold='true',foreground=heading)
 style('def:heading',foreground=heading,bold='true')
 style('def:strong-emphasis',foreground=emphasis,bold='true')
 style('def:emphasis',foreground=emphasis,italic='true')
 style('def:deletion',foreground=muted,strikethrough='true')
 style('def:inline-code',foreground=code,background=codebg)
 style('def:preformatted-section',background=codebg)
 for token in ['link-text','link-destination','net-address']:style('def:'+token,foreground=link,underline='single')
 style('def:list-marker',foreground=listcolor,bold='true')
 for token in ['comment','shebang','thematic-break']:style('def:'+token,foreground=muted,italic='true')
 for token in ['keyword','statement','preprocessor']:style('def:'+token,foreground=code,bold='true')
 for token in ['number','decimal','floating-point','base-n-integer','boolean','constant']:style('def:'+token,foreground=emphasis)
 for token in ['string','character','type']:style('def:'+token,foreground=listcolor)
 for token in ['function','identifier','special-char']:style('def:'+token,foreground=link)
 style('notemd-markdown:marker',foreground=muted)
 style('notemd-markdown:table-header',foreground=heading,bold='true')
 for token,hue in zip(['red','orange','yellow','green','blue','purple'],
    ['#b33142','#9b501f','#80601f','#397148','#3d668c','#6b4fa4'] if name in ['white','solarized-light','catppuccin-latte'] else
    ['#e9959e','#e7b288','#ddca87','#a8ceac','#9abce1','#c2ace4']):
  style('notemd-markdown:'+token,foreground=hue)
 xml='<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/generate-syntax.py. -->\n'
 xml+=f'<style-scheme id="notemd-{name}" name="NoteMD {name}" version="1.0">\n'+'\n'.join(styles)+'\n</style-scheme>\n'
 (root/'syntax'/f'notemd-{name}.xml').write_text(xml)

styles={'marker':'def:comment','code':'def:preformatted-section','strike':'def:deletion','wiki':'def:link-text',
        'task':'def:list-marker','table-header':'def:heading'}
for hue in ['red','orange','yellow','green','blue','purple']:styles[hue]='def:constant'
contexts=[];references=[]
def context(name,content):
 contexts.append('    <context id="'+name+'" '+content+'</context>');references.append('      <context ref="'+name+'"/>')
# Fence delimiter is captured so a backtick fence cannot be closed by tildes.
for language,alias in [('python3','python|python3|py'),('js','javascript|js|jsx'),('typescript','typescript|ts|tsx'),
 ('c','c|h'),('cpp','cpp|c\\+\\+|cxx'),('sh','sh|bash|shell'),('json','json'),('css','css'),('html','html|xml'),
 ('sql','sql'),('rust','rust|rs'),('go','go')]:
 context('fence-'+language,'style-ref="code" class="no-spell-check"><start>'+escape(r'^[ ]{0,3}(`{3,}|~{3,})[ \t]*(?:'+alias+r')[ \t]*$')+
   '</start><end>'+escape(r'^[ ]{0,3}\%{1@start}[`~]*[ \t]*$')+'</end><include><context sub-pattern="0" where="start" style-ref="marker"/>'+
   '<context sub-pattern="0" where="end" style-ref="marker"/><context ref="'+language+':'+language+'"/></include>')
context('fence','style-ref="code" class="no-spell-check"><start>'+escape(r'^[ ]{0,3}(`{3,}|~{3,}).*$')+'</start><end>'+escape(r'^[ ]{0,3}\%{1@start}[`~]*[ \t]*$')+'</end>')
context('task','style-ref="task"><match>'+escape(r'^[ \t]*[-*+]\s+\[[ xX]\]')+'</match>')
context('wiki','style-ref="wiki"><match>'+escape(r'\[\[[^\]\n]+\]\]')+'</match>')
context('strike',r'style-ref="strike"><start>~~(?=\S)</start><end>~~</end><include><context ref="markdown:markdown-syntax"/></include>')
for hue,value in zip(['red','orange','yellow','green','blue','purple'],['#d1242f','#bc4c00','#9a6700','#1a7f37','#0969da','#8250df']):
 context('color-'+hue,'style-ref="'+hue+'"><start>'+escape('<span style="color:'+value+'">')+'</start><end>&lt;/span&gt;</end><include>'+
  '<context sub-pattern="0" where="start" style-ref="marker"/><context sub-pattern="0" where="end" style-ref="marker"/><context ref="markdown:markdown-syntax"/></include>')
context('table-separator','style-ref="marker"><match>'+escape(r'^[ \t]*\|?[ \t]*:?-{3,}:?[ \t]*(?:\|[ \t]*:?-{3,}:?[ \t]*)+\|?[ \t]*$')+'</match>')
context('table-pipe','style-ref="marker"><match>'+escape(r'(?<!\\)\|')+'</match>')
xml='<?xml version="1.0" encoding="UTF-8"?>\n<!-- NoteMD extensions to the system Markdown language. -->\n'
xml+='<language id="notemd-markdown" name="NoteMD Markdown" version="2.0" _section="Markup">\n  <styles>\n'
xml+='\n'.join(f'    <style id="{key}" name="{key}" map-to="{value}"/>' for key,value in styles.items())+'\n  </styles>\n  <definitions>\n'
xml+='\n'.join(contexts)+'\n    <context id="notemd-markdown"><include>\n'+'\n'.join(references)+'\n      <context ref="markdown:markdown-syntax"/>\n      <context ref="html:html"/>\n    </include></context>\n  </definitions>\n</language>\n'
(root/'syntax'/'notemd-markdown.lang').write_text(xml)
